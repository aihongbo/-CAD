import wx
import wx.ribbon as RB


def apply_ribbon_theme(ribbon):
    """蓝灰"""
    art = RB.RibbonMSWArtProvider()

    def set_colour(colour_id, value):
        art.SetColour(colour_id, wx.Colour(value))

    set_colour(RB.RIBBON_ART_TAB_CTRL_BACKGROUND_COLOUR, "#3f4650")
    set_colour(RB.RIBBON_ART_TAB_CTRL_BACKGROUND_GRADIENT_COLOUR, "#3f4650")
    set_colour(RB.RIBBON_ART_TAB_ACTIVE_BACKGROUND_COLOUR, "#ffffff")
    set_colour(RB.RIBBON_ART_TAB_ACTIVE_BACKGROUND_GRADIENT_COLOUR, "#ffffff")
    set_colour(RB.RIBBON_ART_TAB_ACTIVE_BACKGROUND_TOP_COLOUR, "#ffffff")
    set_colour(RB.RIBBON_ART_TAB_ACTIVE_BACKGROUND_TOP_GRADIENT_COLOUR, "#ffffff")
    set_colour(RB.RIBBON_ART_TAB_ACTIVE_LABEL_COLOUR, "#1f2937")
    set_colour(RB.RIBBON_ART_TAB_LABEL_COLOUR, "#ffffff")
    set_colour(RB.RIBBON_ART_TAB_HOVER_BACKGROUND_COLOUR, "#4a525d")
    set_colour(RB.RIBBON_ART_TAB_HOVER_BACKGROUND_GRADIENT_COLOUR, "#4a525d")
    set_colour(RB.RIBBON_ART_TAB_HOVER_BACKGROUND_TOP_COLOUR, "#4a525d")
    set_colour(RB.RIBBON_ART_TAB_HOVER_BACKGROUND_TOP_GRADIENT_COLOUR, "#4a525d")
    set_colour(RB.RIBBON_ART_TAB_HOVER_LABEL_COLOUR, "#ffffff")
    set_colour(RB.RIBBON_ART_PAGE_BACKGROUND_COLOUR, "#f4f5f7")
    set_colour(RB.RIBBON_ART_PAGE_BACKGROUND_GRADIENT_COLOUR, "#f4f5f7")
    set_colour(RB.RIBBON_ART_PAGE_BACKGROUND_TOP_COLOUR, "#f4f5f7")
    set_colour(RB.RIBBON_ART_PAGE_BACKGROUND_TOP_GRADIENT_COLOUR, "#f4f5f7")
    set_colour(RB.RIBBON_ART_PANEL_LABEL_BACKGROUND_COLOUR, "#e2e5e9")
    set_colour(RB.RIBBON_ART_PANEL_LABEL_BACKGROUND_GRADIENT_COLOUR, "#e2e5e9")
    panel_colour = "#f4f5f7"
    button_colour = "#e5e7eb"
    border_colour = "#c7ccd4"

    set_colour(RB.RIBBON_ART_PANEL_HOVER_LABEL_BACKGROUND_COLOUR, "#e2e5e9")
    set_colour(RB.RIBBON_ART_PANEL_HOVER_LABEL_BACKGROUND_GRADIENT_COLOUR, "#e2e5e9")
    set_colour(RB.RIBBON_ART_PANEL_ACTIVE_BACKGROUND_COLOUR, panel_colour)
    set_colour(RB.RIBBON_ART_PANEL_ACTIVE_BACKGROUND_GRADIENT_COLOUR, panel_colour)
    set_colour(RB.RIBBON_ART_PANEL_ACTIVE_BACKGROUND_TOP_COLOUR, panel_colour)
    set_colour(RB.RIBBON_ART_PANEL_ACTIVE_BACKGROUND_TOP_GRADIENT_COLOUR, panel_colour)

    for colour_id in (
        RB.RIBBON_ART_BUTTON_BAR_ACTIVE_BACKGROUND_COLOUR,
        RB.RIBBON_ART_BUTTON_BAR_ACTIVE_BACKGROUND_GRADIENT_COLOUR,
        RB.RIBBON_ART_BUTTON_BAR_ACTIVE_BACKGROUND_TOP_COLOUR,
        RB.RIBBON_ART_BUTTON_BAR_ACTIVE_BACKGROUND_TOP_GRADIENT_COLOUR,
        RB.RIBBON_ART_BUTTON_BAR_HOVER_BACKGROUND_COLOUR,
        RB.RIBBON_ART_BUTTON_BAR_HOVER_BACKGROUND_GRADIENT_COLOUR,
        RB.RIBBON_ART_BUTTON_BAR_HOVER_BACKGROUND_TOP_COLOUR,
        RB.RIBBON_ART_BUTTON_BAR_HOVER_BACKGROUND_TOP_GRADIENT_COLOUR,
        RB.RIBBON_ART_TOOL_BACKGROUND_COLOUR,
        RB.RIBBON_ART_TOOL_BACKGROUND_GRADIENT_COLOUR,
        RB.RIBBON_ART_TOOL_BACKGROUND_TOP_COLOUR,
        RB.RIBBON_ART_TOOL_BACKGROUND_TOP_GRADIENT_COLOUR,
        RB.RIBBON_ART_TOOL_ACTIVE_BACKGROUND_COLOUR,
        RB.RIBBON_ART_TOOL_ACTIVE_BACKGROUND_GRADIENT_COLOUR,
        RB.RIBBON_ART_TOOL_ACTIVE_BACKGROUND_TOP_COLOUR,
        RB.RIBBON_ART_TOOL_ACTIVE_BACKGROUND_TOP_GRADIENT_COLOUR,
        RB.RIBBON_ART_TOOL_HOVER_BACKGROUND_COLOUR,
        RB.RIBBON_ART_TOOL_HOVER_BACKGROUND_GRADIENT_COLOUR,
        RB.RIBBON_ART_TOOL_HOVER_BACKGROUND_TOP_COLOUR,
        RB.RIBBON_ART_TOOL_HOVER_BACKGROUND_TOP_GRADIENT_COLOUR,
    ):
        set_colour(colour_id, button_colour)

    set_colour(RB.RIBBON_ART_BUTTON_BAR_ACTIVE_BORDER_COLOUR, border_colour)
    set_colour(RB.RIBBON_ART_BUTTON_BAR_HOVER_BORDER_COLOUR, border_colour)
    set_colour(RB.RIBBON_ART_BUTTON_BAR_LABEL_HIGHLIGHT_COLOUR, button_colour)
    set_colour(RB.RIBBON_ART_BUTTON_BAR_LABEL_HIGHLIGHT_GRADIENT_COLOUR, button_colour)
    set_colour(RB.RIBBON_ART_BUTTON_BAR_LABEL_HIGHLIGHT_TOP_COLOUR, button_colour)
    set_colour(RB.RIBBON_ART_BUTTON_BAR_LABEL_HIGHLIGHT_GRADIENT_TOP_COLOUR, button_colour)

    ribbon.SetArtProvider(art)
